#include <iostream>
#include <cmath>

using namespace std;

double solveX(double y) {
    return y - (y - sqrt(y));
}

int main() {
    double y;
    cout << "Enter the value of y: ";
    cin >> y;

    double x = solveX(y);
    cout << "The value of x is: " << x << endl;

    return 0;
}


